// 根视图用 `.id(language)` 强制整体重绘，语言切换立即生效。

enum AppLanguage: String, CaseIterable, Identifiable {
    case zhHans = "zh-Hans"
    case en = "en"

    var id: String { rawValue }
    var label: String { self == .zhHans ? "简体中文" : "English" }
}

enum L10n {
    static var current: AppLanguage = .zhHans

    static func tr(_ zh: String) -> String {
        guard current == .en else { return zh }
        return en[zh] ?? zh
    }

    /// 带占位符的整句翻译，避免把句子拼成碎片：
    /// `L10n.tr("期初前有 {} 笔交易。", "3")` → "3 trade(s) before the opening date."
    static func tr(_ zh: String, _ args: String...) -> String {
        var text = tr(zh)
        for arg in args {
            guard let range = text.range(of: "{}") else { break }
            text.replaceSubrange(range, with: arg)
        }
        return text
    }

